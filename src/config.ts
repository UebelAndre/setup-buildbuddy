// Pure logic: turn inputs into rc lines. No I/O here so it can be unit tested
// on any platform.

export type Mode = 'read-write' | 'read-only' | 'anonymous' | 'disabled'

export interface Inputs {
  apiKey: string
  readOnlyApiKey: string
  missingKey: string
  exportEnv: boolean
  authOnly: boolean
  readOnlyDisableUploads: boolean
  remoteEndpoint: string
  appUrl: string
  bes: boolean
  remoteCache: boolean
  remoteExecution: boolean
  remoteTimeout: string
  cacheCompression: boolean
  downloadToplevel: boolean
  visibility: string
  buildMetadata: string
  rcCommand: string
  config: string
  bazelrcPath: string
  flagsFile: string
  bazelrc: string
}

export const DEFAULT_ENDPOINT = 'grpcs://remote.buildbuddy.io'
export const DEFAULT_APP_URL = 'https://app.buildbuddy.io'
export const API_KEY_HEADER = 'x-buildbuddy-api-key'

export const defaultInputs: Inputs = {
  apiKey: '',
  readOnlyApiKey: '',
  missingKey: 'warn',
  exportEnv: false,
  authOnly: false,
  readOnlyDisableUploads: true,
  remoteEndpoint: DEFAULT_ENDPOINT,
  appUrl: DEFAULT_APP_URL,
  bes: true,
  remoteCache: true,
  remoteExecution: false,
  remoteTimeout: '10m',
  cacheCompression: false,
  downloadToplevel: false,
  visibility: '',
  buildMetadata: '',
  rcCommand: 'common',
  config: '',
  bazelrcPath: '',
  flagsFile: '',
  bazelrc: '',
}

/** Accepts the usual spellings of booleans; anything else is false. */
export function truthy(value: string | undefined): boolean {
  return ['true', '1', 'yes', 'on'].includes((value ?? '').trim().toLowerCase())
}

/** Strips whitespace that commonly sneaks into copied secrets. */
export function cleanKey(value: string | undefined): string {
  return (value ?? '').replace(/\s+/g, '')
}

export interface Resolution {
  mode: Mode
  key: string
}

/**
 * Picks the key to use. A write key always wins; otherwise the read-only key;
 * otherwise `missingKey` decides. Throws when configured to error out or when
 * `missingKey` is not a known value.
 */
export function resolveKey(apiKey: string, readOnlyApiKey: string, missingKey: string): Resolution {
  if (apiKey) return { mode: 'read-write', key: apiKey }
  if (readOnlyApiKey) return { mode: 'read-only', key: readOnlyApiKey }
  switch (missingKey || 'warn') {
    case 'warn':
    case 'skip':
      return { mode: 'disabled', key: '' }
    case 'anonymous':
      return { mode: 'anonymous', key: '' }
    case 'error':
      throw new Error('No BuildBuddy API key available and missing-key=error.')
    default:
      throw new Error(`Invalid missing-key value '${missingKey}'. Expected warn, skip, anonymous or error.`)
  }
}

export const MISSING_KEY_MESSAGE =
  'No BuildBuddy API key available (secrets are withheld from fork pull requests). ' +
  'Skipping BuildBuddy configuration; Bazel will run without BuildBuddy.'

/** `common`, or `common:<config>` when a config name is given. */
export function rcPrefix(inputs: Pick<Inputs, 'rcCommand' | 'config'>): string {
  const command = inputs.rcCommand || 'common'
  return inputs.config ? `${command}:${inputs.config}` : command
}

/** File name for the standalone flags file; one per prefix. */
export function flagsFileName(prefix: string): string {
  return `${prefix.replace(/:/g, '-')}.bazelrc`
}

/** Parses `KEY=VALUE` lines, ignoring blanks and `#` comments. */
export function parseBuildMetadata(text: string): string[] {
  const out: string[] = []
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || line.startsWith('#')) continue
    if (!line.includes('=')) {
      throw new Error(`build-metadata line '${line}' is not of the form KEY=VALUE.`)
    }
    out.push(line)
  }
  return out
}

/** The content of the flags file, one rc line per element. */
export function buildLines(inputs: Inputs, resolution: Resolution): string[] {
  const { mode, key } = resolution
  const prefix = rcPrefix(inputs)
  const endpoint = inputs.remoteEndpoint || DEFAULT_ENDPOINT
  const appUrl = (inputs.appUrl || DEFAULT_APP_URL).replace(/\/+$/, '')
  const authOnly = inputs.authOnly

  const lines: string[] = []
  lines.push(
    `# Generated by setup-buildbuddy (mode: ${mode}${authOnly ? ', auth-only' : ''}). ` +
      'Do not edit; rerunning the action rewrites this file.',
  )

  // In auth-only mode the user's own rc decides endpoints and features; we only
  // contribute the credential and the read-only guard.
  let usesRemote = authOnly
  if (!authOnly && inputs.bes) {
    lines.push(`${prefix} --bes_results_url=${appUrl}/invocation/`)
    lines.push(`${prefix} --bes_backend=${endpoint}`)
  }
  if (!authOnly && inputs.remoteCache) {
    lines.push(`${prefix} --remote_cache=${endpoint}`)
    usesRemote = true
  }
  if (!authOnly && inputs.remoteExecution) {
    lines.push(`${prefix} --remote_executor=${endpoint}`)
    usesRemote = true
  }
  if (!authOnly && usesRemote && inputs.remoteTimeout) {
    lines.push(`${prefix} --remote_timeout=${inputs.remoteTimeout}`)
  }
  if (mode === 'read-only' && usesRemote && inputs.readOnlyDisableUploads) {
    // The key cannot upload anyway; skip the attempts so Bazel does not spend
    // time and log warnings on rejected writes. BES still receives logs.
    lines.push(`${prefix} --noremote_upload_local_results`)
  }
  if (!authOnly && usesRemote && inputs.cacheCompression) {
    lines.push(`${prefix} --remote_cache_compression`)
  }
  if (!authOnly && usesRemote && inputs.downloadToplevel) {
    lines.push(`${prefix} --remote_download_toplevel`)
  }

  if (!authOnly) {
    // BuildBuddy derives REPO_URL, COMMIT_SHA, BRANCH_NAME and USER from the
    // GITHUB_* environment; ROLE=CI is set explicitly for clarity.
    lines.push(`${prefix} --build_metadata=ROLE=CI`)
    if (inputs.visibility) {
      lines.push(`${prefix} --build_metadata=VISIBILITY=${inputs.visibility}`)
    }
    for (const md of parseBuildMetadata(inputs.buildMetadata)) {
      lines.push(`${prefix} --build_metadata=${md}`)
    }
  }

  if (key) {
    // --remote_header is applied to BES, remote cache and remote execution
    // requests, and Bazel redacts it from its own logs.
    lines.push(`${prefix} --remote_header=${API_KEY_HEADER}=${key}`)
  }

  if (inputs.bazelrc.trim()) {
    // Multiline YAML inputs end with a newline; drop that one trailing blank.
    for (const extra of inputs.bazelrc.replace(/\r?\n$/, '').split(/\r?\n/)) {
      lines.push(extra)
    }
  }
  return lines
}

/** Hides the key in a line destined for the log. */
export function maskLine(line: string): string {
  return line.replace(new RegExp(`(${API_KEY_HEADER}=).*$`), '$1***')
}
